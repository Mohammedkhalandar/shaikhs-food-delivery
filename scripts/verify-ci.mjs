import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import yaml from 'js-yaml';
const workflow = yaml.load(await fs.readFile('.github/workflows/verify.yml', 'utf8'));
assert.deepEqual(workflow.permissions, { contents: 'read' });
assert.equal(workflow.jobs.verify['timeout-minutes'], 20);
assert.equal(workflow.jobs.verify.env.RAZORPAY_SANDBOX_VERIFIED, 'false');
const steps = workflow.jobs.verify.steps;
assert.equal(workflow.jobs.verify.services.postgres.image, 'postgres:16-alpine');
const postgresTools = steps.find(step => step.env?.POSTGRES_CONTAINER === '${{ job.services.postgres.id }}');
assert.ok(postgresTools?.run.includes('pg_dump pg_restore psql') && postgresTools.run.includes('set -euo pipefail'));
assert.ok(postgresTools.run.includes('PG_TOOL_DOCKER_CONTAINER=$POSTGRES_CONTAINER') && postgresTools.run.includes('16\\.'));
assert.ok(!workflow.jobs.verify.env.PG_BIN && !steps.some(step => step.run?.includes('apt-get install -y postgresql-client-16')));
const server = steps.find(step => step.run?.includes('server_pid=')).run;
assert.ok(server.includes('npm run test:customer-design'));
assert.ok(server.includes('set -euo pipefail') && server.includes('if [ "$ready" != true ]'));
assert.ok(server.includes('node node_modules/next/dist/bin/next start'));
assert.ok(server.includes('kill "$server_pid"'));
for (const suite of ['test:payments:http', 'test:e2e', 'test:management', 'test:addresses-zones', 'test:recovery-notifications', 'test:restaurant-finance', 'test:administration', 'test:inventory', 'test:cases', 'test:email-verification', 'test:commerce', 'test:checkout-ui', 'test:release-ui', 'test:release-http', 'test:web-acceptance', 'test:pwa-catalog', 'test:low-network']) assert.ok(server.includes(suite));
const artifacts = steps.find(step => step.uses?.startsWith('actions/upload-artifact@')).with.path;
assert.ok(artifacts.includes('**/*.png') && !artifacts.split('\n').includes('.test-artifacts/'));
for(const gate of ['npm ci','npm audit --audit-level=moderate','npm test','npm run test:backup-restore','npm run test:deployment','npm run lint','npm run typecheck','prisma validate','npm run build'])assert.ok(steps.some(step=>step.run?.includes(gate)));
assert.ok(!artifacts.includes('.backups'));
console.log('PASS: static CI permissions, timeout, fail-closed readiness, direct PID cleanup, test suites and artifact allowlist (not a remote CI run)');
